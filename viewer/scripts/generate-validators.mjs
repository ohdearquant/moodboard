import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const viewerRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(viewerRoot, "..");
const outputPath = path.join(viewerRoot, "src", "generated", "report-validators.mjs");
const schemas = [
  ["report-v1.0", path.join(repositoryRoot, "moodboard", "schema", "report_v1_0.schema.json")],
  ["report-v1.1", path.join(repositoryRoot, "moodboard", "schema", "report_v1_1.schema.json")],
];

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  validateFormats: false,
  allowUnionTypes: true,
  code: { source: true, esm: true, lines: true },
});
const digests = [];
for (const [key, schemaPath] of schemas) {
  const bytes = await readFile(schemaPath);
  const schema = JSON.parse(bytes.toString("utf8"));
  ajv.addSchema(schema, key);
  digests.push(`${key}=${createHash("sha256").update(bytes).digest("hex")}`);
}

const generated = [
  "// Generated by scripts/generate-validators.mjs; do not edit.",
  `// Exact inputs: ${digests.join(", ")}`,
  standaloneCode(ajv, {
    validateReportV10: "report-v1.0",
    validateReportV11: "report-v1.1",
  }).trimEnd(),
  "",
].join("\n");

const mode = process.argv[2];
if (mode === "--write") {
  await writeFile(outputPath, generated, "utf8");
} else if (mode === "--check") {
  let existing;
  try {
    existing = await readFile(outputPath, "utf8");
  } catch {
    throw new Error("Generated report validators are absent; run `npm run validators:write`.");
  }
  if (existing !== generated) {
    throw new Error("Generated report validators differ from the exact schemas; run `npm run validators:write`.");
  }
} else {
  throw new Error("Usage: node scripts/generate-validators.mjs --write|--check");
}
